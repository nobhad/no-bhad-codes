/**
 * ===============================================
 * CARD BACK — IMPORT AND REFIT
 * ===============================================
 * @file scripts/refit-card-back.mjs
 *
 * Pulls the latest card-back export out of the design tree and fits it to the
 * card the intro animation actually uses.
 *
 * WHY A FIT IS NEEDED AT ALL
 *
 * The Illustrator artboard draws a 1352.31 x 772.75 card — aspect 1.7500. The
 * card the back has to flip against is the one drawn INSIDE coyote_paw.svg, at
 * 1060.5 x 590.3 — aspect 1.7965 — because the intro hands the card from the
 * paw to the DOM and the two faces have to share an edge. Those are differently
 * PROPORTIONED cards, not just differently sized ones, so no single scale maps
 * one onto the other and something has to give.
 *
 * It gives on the margin, not the type: the artwork is scaled UNIFORMLY by the
 * tighter axis (height) and centred, and the outline is drawn at the paw
 * scene's dimensions. Filling the card instead would need 0.784 x 0.764, which
 * widens the lettering by 2.66% — and distorting type to reclaim a margin
 * nobody will notice is the wrong way round.
 *
 * DO NOT "FIX" THIS BY RE-EXPORTING coyote_paw.svg
 *
 * The current artboard exports the paw with every layer renamed to paw1..paw4.
 * All 17 ids in SVG_ELEMENT_IDS — Arm_Base, Position_1..3, every finger and
 * thumb — disappear with them, and the intro animation stops finding anything.
 * The card travels between the two files; the paw does not.
 *
 * Run: npm run card:back
 */

import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const SRC =
  '/Users/noellebhaduri/Projects/Design/no-bhad-codes/illustrator/business_card_animations/SVG/intro_pawCard_Back.svg';
const OUT = 'public/images/business-card_back-v2.svg';
const FRONT = 'public/images/business-card_front.svg';

/** Read a card's outline rect — the visible card edge, minus its stroke. */
function outlineOf(file) {
  const svg = readFileSync(file, 'utf8');
  const rect = svg.match(/<rect[^>]*id="_?Card_Outline_?"[^>]*>/);
  if (!rect) throw new Error(`no Card_Outline rect in ${file}`);
  const num = (k) => {
    const m = rect[0].match(new RegExp(`\\b${k}="([\\d.]+)"`));
    if (!m) throw new Error(`${file}: outline rect has no ${k}`);
    return parseFloat(m[1]);
  };
  const vb = svg.match(/viewBox="([^"]+)"/);
  if (!vb) throw new Error(`no viewBox in ${file}`);
  const [, , vw, vh] = vb[1].split(/\s+/).map(Number);
  return { x: num('x'), y: num('y'), w: num('width'), h: num('height'), vw, vh, svg, rect: rect[0] };
}

if (!existsSync(SRC)) {
  console.error(`No export at:\n  ${SRC}\nExport the card back from Illustrator first.`);
  process.exit(1);
}

// The FRONT is the reference, because it is already aligned to coyote_paw.svg.
const t = outlineOf(FRONT);
const s = outlineOf(SRC);

const scale = Math.min(t.w / s.w, t.h / s.h);
const aw = s.w * scale;
const ah = s.h * scale;
const tx = t.x + (t.w - aw) / 2 - s.x * scale;
const ty = t.y + (t.h - ah) / 2 - s.y * scale;
const margin = (t.w - aw) / 2;

// Strip the export's own outline; the front's rect is authoritative.
let body = s.svg.slice(s.svg.indexOf('>', s.svg.indexOf('<svg')) + 1, s.svg.lastIndexOf('</svg>'));
const own = body.match(/\s*<rect[^>]*id="Card_Outline"[^>]*\/>/);
if (own) body = body.replace(own[0], '');

writeFileSync(
  OUT,
  `<?xml version="1.0" encoding="UTF-8"?>
<!-- GENERATED by scripts/refit-card-back.mjs — do not hand-edit.
     Source: ${SRC.split('/').slice(-1)[0]} (${s.w} x ${s.h}, aspect ${(s.w / s.h).toFixed(4)})
     Fitted to the front (${t.w} x ${t.h}, aspect ${(t.w / t.h).toFixed(4)}), which is
     itself aligned to the card inside coyote_paw.svg. Uniform scale ${scale.toFixed(6)},
     ${margin.toFixed(1)}px of margin each side. See the script for why. -->
<svg id="card_back" xmlns="http://www.w3.org/2000/svg" width="${t.vw}" height="${t.vh}" viewBox="0 0 ${t.vw} ${t.vh}">
  <rect id="Card_Outline" x="${t.x}" y="${t.y}" width="${t.w}" height="${t.h}" fill="#fff" stroke="#000" stroke-miterlimit="10" stroke-width="9"/>
  <g transform="translate(${tx.toFixed(4)} ${ty.toFixed(4)}) scale(${scale.toFixed(6)})">${body}</g>
</svg>
`
);

console.log(`card back → ${OUT}`);
console.log(`  source   ${s.w} x ${s.h}   aspect ${(s.w / s.h).toFixed(4)}`);
console.log(`  target   ${t.w} x ${t.h}   aspect ${(t.w / t.h).toFixed(4)}`);
console.log(`  scale    ${scale.toFixed(6)} (uniform, ${t.h / s.h < t.w / s.w ? 'height' : 'width'}-constrained)`);
console.log(`  artwork  ${aw.toFixed(2)} x ${ah.toFixed(2)}, ${margin.toFixed(1)}px margin each side`);
